-- Chart of accounts. Cash accounts are created here.
CREATE TABLE "OACT" (
    "AcctCode"   VARCHAR(15)    PRIMARY KEY,
    "AcctName"   VARCHAR(200)   NOT NULL,
    "FormatCode" VARCHAR(210),
    "CurrTotal"  NUMERIC(19, 6) NOT NULL DEFAULT 0,
    "Finanse"    VARCHAR(1)     NOT NULL DEFAULT 'N' CHECK ("Finanse" IN ('Y', 'N')),
    "Postable"   VARCHAR(1)     NOT NULL DEFAULT 'Y' CHECK ("Postable" IN ('Y', 'N')),
    "FatherNum"  VARCHAR(15)    REFERENCES "OACT" ("AcctCode"),
    "Levels"     INT            NOT NULL DEFAULT 1,
    "ActType"    VARCHAR(1)     NOT NULL DEFAULT 'N' CHECK ("ActType" IN ('I', 'E', 'N'))
);

-- Default accounts: which account each kind of operation posts to. Columns come from the SDK.
CREATE TABLE "OACP" (
    "AbsEntry"   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PeriodCat"  VARCHAR(10) NOT NULL,
    "FinancYear" DATE,
    "LinkAct_1"  VARCHAR(15) REFERENCES "OACT" ("AcctCode"),
    "LinkAct_3"  VARCHAR(15) REFERENCES "OACT" ("AcctCode"),
    "DfltIncom"  VARCHAR(15) REFERENCES "OACT" ("AcctCode"),
    "DfltExpn"   VARCHAR(15) REFERENCES "OACT" ("AcctCode")
);
